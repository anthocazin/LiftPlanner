// Builds dist/LiftPlanner.html: the whole application in ONE file, usable offline
// (double-click, file://), pdf.js included; and the same for LiftPlanner Light (light/index.html).
// No dependencies: node tools/build-standalone.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve, relative, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
let modules = new Map(); // abs path -> { header, src, exported }
let order = [];

function parse(file, stack = []) {
  if (modules.has(file)) return;
  if (stack.includes(file)) throw new Error(`Circular import: ${[...stack, file].map((f) => relative(ROOT, f)).join(' → ')}`);
  let src = readFileSync(file, 'utf8');
  const deps = [];
  const header = [];
  const id = (p) => JSON.stringify(relative(ROOT, p));
  src = src.replace(/import\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"];?/gs, (_, names, spec) => {
    const dep = resolve(dirname(file), spec);
    deps.push(dep);
    const binds = names
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean)
      .map((s) => s.replace(/\s+as\s+/, ': '));
    header.push(`const { ${binds.join(', ')} } = __m[${id(dep)}];`);
    return '';
  });
  src = src.replace(/import\s*\*\s*as\s+(\w+)\s+from\s*['"]([^'"]+)['"];?/g, (_, ns, spec) => {
    const dep = resolve(dirname(file), spec);
    deps.push(dep);
    header.push(`const ${ns} = __m[${id(dep)}];`);
    return '';
  });
  if (/^\s*import\s/m.test(src)) throw new Error(`Unsupported import in ${relative(ROOT, file)}`);
  const exported = [];
  src = src.replace(/^export\s+(async\s+function|function\*?|const|let|var|class)\s+([A-Za-z_$][\w$]*)/gm, (_, kw, name) => {
    exported.push(name);
    return `${kw} ${name}`;
  });
  src = src.replace(/^export\s*\{([^}]*)\};?/gm, (_, names) => {
    names.split(',').map((s) => s.trim()).filter(Boolean).forEach((n) => exported.push(n));
    return '';
  });
  if (/^export\s/m.test(src)) throw new Error(`Unsupported export in ${relative(ROOT, file)}`);
  stack.push(file);
  deps.forEach((d) => parse(d, stack));
  stack.pop();
  modules.set(file, { header, src, exported });
  order.push(file);
}

function bundleOf(entry) {
  modules = new Map();
  order = [];
  parse(join(ROOT, entry));
  return order
  .map((f) => {
    const m = modules.get(f);
    const name = JSON.stringify(relative(ROOT, f));
    return `// ---- ${relative(ROOT, f)}\n__m[${name}] = (() => {\n${m.header.join('\n')}\n${m.src}\nreturn { ${[...new Set(m.exported)].join(', ')} };\n})();`;
  })
  .join('\n\n').replace(/<\/script/gi, '<\\/script');
}

const bundle = bundleOf('js/ui/main.js');
const nMain = order.length;
const css = readFileSync(join(ROOT, 'css/app.css'), 'utf8');
let html = readFileSync(join(ROOT, 'app.html'), 'utf8');
const b64 = (p) => readFileSync(join(ROOT, p)).toString('base64');
const pdfjs = b64('vendor/pdfjs/pdf.min.mjs');
const worker = b64('vendor/pdfjs/pdf.worker.min.mjs');
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));

const boot = `
<script>
(function(){
  function blobUrl(b64){ var s = atob(b64), u = new Uint8Array(s.length); for (var i = 0; i < s.length; i++) u[i] = s.charCodeAt(i); return URL.createObjectURL(new Blob([u], { type: 'text/javascript' })); }
  window.__PDFJS_URL = blobUrl(document.getElementById('pdfjs-b64').textContent.trim());
  window.__PDFJS_WORKER_URL = blobUrl(document.getElementById('pdfjs-worker-b64').textContent.trim());
})();
</script>`;

html = html
  .replace(/<link rel="stylesheet" href="css\/app.css" \/>/, `<style>\n${css}\n</style>`)
  .replace(
    /<script type="module" src="js\/ui\/main.js"><\/script>/,
    `<script type="text/plain" id="pdfjs-b64">${pdfjs}</script>\n<script type="text/plain" id="pdfjs-worker-b64">${worker}</script>\n${boot}\n<script type="module">\n// LiftPlanner v${pkg.version} — standalone build generated by tools/build-standalone.mjs\nconst __m = {};\n${bundle}\n</script>`,
  );

// build id (hash of the content): an open page compares it with version.json and offers to reload
const build = createHash('sha1').update(html).digest('hex').slice(0, 10);
html = html.replace('</head>', `  <meta name="build" content="${build}" />\n</head>`);
mkdirSync(join(ROOT, 'dist'), { recursive: true });
writeFileSync(join(ROOT, 'dist/LiftPlanner.html'), html);
// the published site is this single file: a reload always gets the whole new version
writeFileSync(join(ROOT, 'index.html'), html);
writeFileSync(join(ROOT, 'version.json'), `${JSON.stringify({ build, version: pkg.version })}\n`);
console.log(`dist/LiftPlanner.html + index.html — ${(html.length / 1024).toFixed(0)} Ko, ${nMain} modules, build ${build}`);

// ---- LiftPlanner Light: light/index.html (and dist/LiftPlannerLight.html), no pdf.js
const lbundle = bundleOf('js/light/main.js');
let light = readFileSync(join(ROOT, 'light/dev.html'), 'utf8')
  .replace(/<link rel="stylesheet" href="..\/css\/light.css" \/>/, () => `<style>\n${readFileSync(join(ROOT, 'css/light.css'), 'utf8')}\n</style>`)
  .replace(/<script type="module" src="..\/js\/light\/main.js"><\/script>/, () => `<script type="module">\n// LiftPlanner Light v${pkg.version} — standalone build generated by tools/build-standalone.mjs\nconst __m = {};\n${lbundle}\n</script>`);
if (light.includes('src="../js/')) throw new Error('light/dev.html: entry script not replaced');
const lbuild = createHash('sha1').update(light).digest('hex').slice(0, 10);
light = light.replace('</head>', `  <meta name="build" content="${lbuild}" />\n</head>`);
writeFileSync(join(ROOT, 'light/index.html'), light);
writeFileSync(join(ROOT, 'dist/LiftPlannerLight.html'), light);
writeFileSync(join(ROOT, 'light/version.json'), `${JSON.stringify({ build: lbuild, version: pkg.version })}\n`);
console.log(`light/index.html — ${(light.length / 1024).toFixed(0)} Ko, ${order.length} modules, build ${lbuild}`);
